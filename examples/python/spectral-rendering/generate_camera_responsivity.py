"""Regenerate the camera example from pinned rawtoaces data; run with uv run --script."""

import json
from pathlib import Path

import colour
import numpy as np

root = Path(__file__).resolve().parent
spectra = {}
for name in ("cmf_1931", "training_spectral", "Canon_EOS_5D_380_780_5", "Sony_ILCE-7M4_380_780_5"):
    document = json.loads((root / "camera-data" / f"{name}.json").read_text())
    pairs = sorted(document["spectral_data"]["data"]["main"].items(), key=lambda item: float(item[0]))
    spectra[name] = (np.array([float(w) for w, _ in pairs]), np.array([v for _, v in pairs]))

# Integrate the piecewise-linear source curves on a 1 nm grid over their shared domain.
# Match the example's 6504 K CIE daylight illuminant, rather than a blackbody or an RGB white.
wavelengths = np.arange(380.0, 781.0)
weights = np.ones_like(wavelengths)
weights[[0, -1]] = 0.5
illuminant = colour.sd_CIE_illuminant_D_series(colour.temperature.CCT_to_xy_CIE_D(6504.0))
daylight = np.interp(wavelengths, illuminant.wavelengths, illuminant.values)
resampled = {}
for name, (source_wavelengths, values) in spectra.items():
    resampled[name] = np.column_stack([
        np.interp(wavelengths, source_wavelengths, channel) for channel in values.T
    ])
cmfs = resampled["cmf_1931"]
patches = resampled["training_spectral"]
weighted_light = daylight * weights
normalization = weighted_light @ cmfs[:, 1]
xyz = (patches.T * weighted_light) @ cmfs / normalization
white_xyz = weighted_light @ cmfs / normalization

# The source files supply relative sensor curves, not vendor color matrices.
# Fit one camera-to-XYZ matrix per camera to the 190 reference reflectances under D65.
# Constrain a perfect reflector to the CIE white; keep this same transform under sodium.
report = {"illuminant": "CIE daylight, 6504 K", "domain_nm": [380, 780], "cameras": {}}
lines = [
    '#usda 1.0',
    '# Generated by generate_camera_responsivity.py. Do not edit sampled data by hand.',
    '# Camera curves: rawtoaces-data, Apache-2.0. See CAMERA_RESPONSIVITY.md and RAWTOACES-LICENSE.',
    'over "World" {',
]
for name, prim in (("Canon_EOS_5D_380_780_5", "Canon5D"), ("Sony_ILCE-7M4_380_780_5", "SonyA7IV")):
    response = resampled[name]
    rgb = (patches.T * weighted_light) @ response / normalization
    white_rgb = weighted_light @ response / normalization
    system = np.zeros((4, 4))
    system[:3, :3] = rgb.T @ rgb
    system[:3, 3] = white_rgb
    system[3, :3] = white_rgb
    target = np.vstack((rgb.T @ xyz, white_xyz))
    camera_to_xyz = np.linalg.solve(system, target)[:3].T
    residual = rgb @ camera_to_xyz.T - xyz
    report["cameras"][prim] = {
        "camera_to_xyz": camera_to_xyz.tolist(),
        "training_xyz_rmse": float(np.sqrt(np.mean(residual ** 2))),
        "white_xyz": (camera_to_xyz @ white_rgb).tolist(),
        "target_white_xyz": white_xyz.tolist(),
    }
    print(prim, 'training XYZ RMSE:', report['cameras'][prim]['training_xyz_rmse'])
    lines += [
        f'    def Camera "{prim}" (',
        '        prepend references = </World/Camera>',
        '        prepend apiSchemas = ["PhysicalCameraResponsivityAPI"]',
        '    ) {',
        '        # Use the same geometry and exposure as the default CIE camera.',
        '        # White balance is included in the fixed D65 matrix below.',
        '        float physical:responsivity:colorTemperature = 0',
    ]
    source_wavelengths, values = spectra[name]
    for channel, samples in zip('rgb', values.T):
        lines.append(f'        float2[] physical:responsivity:{channel} = [')
        lines.extend(f'            ({w:g}, {v:.17g}),' for w, v in zip(source_wavelengths, samples))
        lines.append('        ]')
    rows = ', '.join('(' + ', '.join(f'{v:.17g}' for v in row) + ')' for row in camera_to_xyz)
    lines += [f'        matrix3d physical:responsivity:cameraToXYZ = ({rows})', '    }']
lines.append('}')
(root / 'camera_responsivity.usda').write_text('\n'.join(lines) + '\n')
(root / 'camera-data' / 'calibration.json').write_text(json.dumps(report, indent=2) + '\n')
