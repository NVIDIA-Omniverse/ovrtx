"""Check that every sensors page keeps the shape its kind of page promises.

The sensors documentation gives each kind of page a consistent structure, so a reader
who has learned one model's pages finds the next model's pages laid out the
same way: an overview answers the same questions in the same order, a how-to
introduces its purpose and assumptions first and ends with how to verify the
result and what to check when it is wrong, an outputs page opens with how to
request the output. Sphinx checks none of this. A renamed, dropped or reordered
section leaves the build green while the page quietly stops matching its
siblings, so the skeletons are asserted here:

- every page starts with the SPDX comment header shared across the tree,
  carries a ``.. _sensors-...:`` label directly above its title and ends with a
  ``Related`` section (the generated schema references are the one exception);
- a model overview carries the overview sections in the agreed relative order;
- a how-to page introduces the task before its first section, includes
  ``Before you start`` and carries ``Verification`` before ``Potential issues``;
  camera references outside a ``howto/`` directory retain their own shape;
- a non-visual outputs page opens with ``Requesting the output`` and keeps its
  ``Channels`` and ``Params`` sections;
- an attributes page does not open with a subsection before its first section;
- every figure or image directive carries a sizing option, ``:width:`` set to
  the file's own width or an intentional responsive size, which is what makes Sphinx link the image to its file
  so that a reader can open it on its own (``html_scaled_image_link``).

Headings are read the way docutils reads the underline styles this tree uses:
a title line followed by a line of one repeated character (``=`` title, ``-``
section, ``^`` subsection, ``~`` sub-subsection) at least as long as the title.
Pages under a subtree that ``docs/conf.py`` excludes from the build are not
held to the skeletons. Pure standard library, so it runs wherever the USDA
suite runs.
"""

import re
from collections import namedtuple
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCS = REPO_ROOT / "docs"
SENSORS = DOCS / "sensors"

# The nine-line comment header every page opens with; only the copyright year varies.
HEADER_FIRST = re.compile(
    r"^\.\. SPDX-FileCopyrightText: Copyright \(c\) \d{4}(?:-\d{4})? "
    r"NVIDIA CORPORATION & AFFILIATES\. All rights reserved\.$"
)
HEADER_REST = [
    ".. SPDX-License-Identifier: LicenseRef-NvidiaProprietary",
    "..",
    ".. NVIDIA CORPORATION, its affiliates and licensors retain all intellectual",
    ".. property and proprietary rights in and to this material, related",
    ".. documentation and any modifications thereto. Any use, reproduction,",
    ".. disclosure or distribution of this material and related documentation",
    ".. without an express license agreement from NVIDIA CORPORATION or",
    ".. its affiliates is strictly prohibited.",
]
HEADER_LINES = 1 + len(HEADER_REST)

# Subtrees that docs/conf.py keeps out of the build, each with the reason.
EXCLUDED_SUBTREES = {
    "sensors/nonvisual/idealized_depth": "drafted and held back from the build by docs/conf.py",
}

# Pages allowed to end without a Related section, each with the reason.
NO_RELATED = {
    "sensors/reference/schemas.rst": (
        "generated by schemas/omni_sensors/generate-schema-docs.py, which writes no Related section"
    ),
    "sensors/reference/schemas_lens_distortion.rst": (
        "generated by schemas/omni_sensors/generate-schema-docs.py, which writes no Related section"
    ),
}

# Section titles a model overview carries, in this relative order; other sections may sit between.
OVERVIEW_SECTIONS = [
    "Simulation",
    "Outputs",
    "Applications",
    "Sensor definition",
    "Configuration and outputs",
    "Related",
]
# Visual sensor pages retain their existing titles until their own editorial pass.
# Normalize titles without dropping the required topic/order checks.
SECTION_ALIASES = {
    "What it simulates": "Simulation",
    "What you get": "Outputs",
    "When to use it": "Applications",
    "How it is authored": "Sensor definition",
    "Pages under this model": "Configuration and outputs",
    "Verify it worked": "Verification",
    "When it goes wrong": "Potential issues",
}
# Section titles a how-to page closes with, in this order, before Related.
HOWTO_CLOSING_SECTIONS = ["Verification", "Potential issues"]
# The assumptions lead-in: bold, or a sentence that starts with the words.
BEFORE_YOU_START = re.compile(r"(?:^|[.!?]\s+|\*\*)Before you start\b", re.MULTILINE)

UNDERLINE = re.compile(r"^([=\-^~])\1*\s*$")
LABEL = re.compile(r"^\.\. _([^:\s]+):\s*$")

# ``lineno`` is the 1-based line number of the title line.
Heading = namedtuple("Heading", "lineno char title")


def _rel(rst):
    """The page's path relative to the docs root, with forward slashes."""
    return rst.relative_to(DOCS).as_posix()


def _pages():
    for rst in sorted([*SENSORS.rglob("*.rst"), DOCS / "materials/nonvisual_sensor_materials.rst"]):
        if "_build" in rst.parts:
            continue
        if any(_rel(rst).startswith(subtree + "/") for subtree in EXCLUDED_SUBTREES):
            continue
        yield rst


def _headings(lines):
    """Yield a Heading for every title line followed by a long-enough underline."""
    for i in range(1, len(lines)):
        title, underline = lines[i - 1], lines[i]
        if not title.strip() or title[0].isspace() or UNDERLINE.match(title):
            continue
        if not UNDERLINE.match(underline) or len(underline.rstrip()) < len(title.rstrip()):
            continue
        yield Heading(i, underline[0], title.rstrip())


def _read(rst):
    """The page's lines and its headings."""
    lines = rst.read_text(encoding="utf-8").splitlines()
    return lines, list(_headings(lines))


def _sections(headings):
    """The titles of the ``-`` level headings, in page order."""
    return [h.title for h in headings if h.char == "-"]


def _order_problems(found, wanted):
    """Say which of ``wanted`` is missing from ``found`` or out of the wanted relative order."""
    problems = [f"has no section {title!r}" for title in wanted if title not in found]
    present = [title for title in wanted if title in found]
    if [found.index(title) for title in present] != sorted(found.index(title) for title in present):
        actual = sorted(present, key=found.index)
        problems.append(f"sections out of order: found {actual}, wanted {present}")
    return problems


def _matching(*patterns):
    """The pages whose docs-relative path matches one of the patterns, segment by segment."""
    found = [p for p in PAGES if any(p.relative_to(DOCS).match(pattern) for pattern in patterns)]
    assert found, f"no page matches {patterns}; the docs tree moved"
    return found


def _ids(pages):
    return [_rel(p) for p in pages]


PAGES = list(_pages())
assert PAGES, "no pages found under docs/sensors; the docs tree moved"

MODEL_OVERVIEWS = _matching("sensors/nonvisual/*/index.rst", "sensors/visual/*/index.rst")
NONVISUAL_OUTPUTS = _matching("sensors/nonvisual/*/outputs.rst")
ATTRIBUTES = _matching(
    "sensors/nonvisual/*/attributes.rst", "sensors/visual/*/attributes.rst", "sensors/cameras/usd_camera_attributes.rst"
)
HOWTOS = [
    p for p in PAGES
    if "howto" in p.relative_to(DOCS).parts and p.name != "index.rst"
]
assert HOWTOS, "no how-to pages found; the docs tree moved"


@pytest.mark.parametrize("rst", PAGES, ids=_ids(PAGES))
def test_page_frame(rst):
    """The shared header, a ``sensors-`` label bound to the title, and Related as the last section."""
    rel = _rel(rst)
    lines, headings = _read(rst)
    problems = []

    head = lines[:HEADER_LINES]
    if len(head) < HEADER_LINES or not HEADER_FIRST.match(head[0]) or head[1:] != HEADER_REST:
        problems.append("does not start with the nine-line SPDX comment header the tree shares")

    titles = [h for h in headings if h.char == "="]
    if not titles:
        problems.append("has no title (a line underlined with =)")
    else:
        before = lines[: titles[0].lineno - 1]
        nearest = next((line for line in reversed(before) if line.strip()), "")
        labels = [m.group(1) for line in before if (m := LABEL.match(line))]
        if not LABEL.match(nearest):
            problems.append(
                f"the line above the title is {nearest!r}, not a label, so no label binds to the title"
            )
        if not any(label.startswith("sensors-") for label in labels):
            problems.append("has no '.. _sensors-...:' label before its title")

    if rel not in NO_RELATED:
        last = headings[-1] if headings else None
        if last is None or (last.char, last.title) != ("-", "Related"):
            ending = f"{last.title!r} ({last.char})" if last else "no heading at all"
            problems.append(f"the last heading is {ending}, not a 'Related' section (-)")

    assert not problems, f"{rel}:\n- " + "\n- ".join(problems)


@pytest.mark.parametrize("rst", MODEL_OVERVIEWS, ids=_ids(MODEL_OVERVIEWS))
def test_model_overview_sections(rst):
    """The overview sections are present and in the agreed relative order."""
    _, headings = _read(rst)
    sections = [SECTION_ALIASES.get(title, title) for title in _sections(headings)]
    problems = _order_problems(sections, OVERVIEW_SECTIONS)
    assert not problems, f"{_rel(rst)}:\n- " + "\n- ".join(problems) + f"\n  sections found: {sections}"


@pytest.mark.parametrize("rst", HOWTOS, ids=_ids(HOWTOS))
def test_howto_shape(rst):
    """Introductory prose and prerequisites, then verification before potential issues.

    Related being the last section is test_page_frame's check.
    """
    lines, headings = _read(rst)
    text = "\n".join(lines)
    sections = [SECTION_ALIASES.get(title, title) for title in _sections(headings)]
    problems = []
    title = next(h for h in headings if h.char == "=")
    first_section = next(h for h in headings if h.char == "-")
    introduction = lines[title.lineno + 1:first_section.lineno - 1]
    if not any(line and not line.startswith(("..", " ")) for line in introduction):
        problems.append("has no introductory prose before its first section")
    if not BEFORE_YOU_START.search(text):
        problems.append("has no 'Before you start' lead-in, bold or as a sentence")
    problems += _order_problems(sections, HOWTO_CLOSING_SECTIONS)
    assert not problems, f"{_rel(rst)}:\n- " + "\n- ".join(problems) + f"\n  sections found: {sections}"


@pytest.mark.parametrize("rst", NONVISUAL_OUTPUTS, ids=_ids(NONVISUAL_OUTPUTS))
def test_nonvisual_outputs_sections(rst):
    """The page opens with how to request the output and keeps its Channels and Params sections."""
    _, headings = _read(rst)
    sections = [SECTION_ALIASES.get(title, title) for title in _sections(headings)]
    problems = []
    first = sections[0] if sections else None
    if first != "Requesting the output":
        problems.append(f"the first section is {first!r}, not 'Requesting the output'")
    problems += [f"has no section {title!r}" for title in ("Channels", "Params") if title not in sections]
    assert not problems, f"{_rel(rst)}:\n- " + "\n- ".join(problems) + f"\n  sections found: {sections}"


@pytest.mark.parametrize("rst", ATTRIBUTES, ids=_ids(ATTRIBUTES))
def test_attributes_open_with_a_section(rst):
    """No ``^`` subsection appears before the page's first ``-`` section."""
    _, headings = _read(rst)
    body = [h for h in headings if h.char != "="]
    first_section = next((i for i, h in enumerate(body) if h.char == "-"), len(body))
    early = [h.title for h in body[:first_section] if h.char == "^"]
    assert not early, f"{_rel(rst)}: subsection(s) {early} appear before the first section"


# An image directive, also inside a list-table cell (``* - .. image::``) or a bullet.
IMAGE_DIRECTIVE = re.compile(r"^\s*(?:\* - |- )?\.\. (?:figure|image)::\s*\S+\s*$")
SIZING_OPTION = re.compile(r"^\s*:(?:width|height|scale):")


def _unsized_images(lines):
    """1-based line numbers of the image directives whose option block has no sizing option.

    The option block runs from the line after the directive to the first blank line or the
    first line indented no deeper than the directive itself; wrapped option values belong to it.
    """
    found = []
    for i, line in enumerate(lines):
        if not IMAGE_DIRECTIVE.match(line):
            continue
        directive_indent = line.index(".. ")
        j = i + 1
        while j < len(lines) and lines[j].strip() and len(lines[j]) - len(lines[j].lstrip()) > directive_indent:
            j += 1
        if not any(SIZING_OPTION.match(option) for option in lines[i + 1 : j]):
            found.append(i + 1)
    return found


@pytest.mark.parametrize("rst", PAGES, ids=_ids(PAGES))
def test_figures_carry_a_width(rst):
    """Every figure or image directive carries ``:width:`` (or another sizing option).

    Sphinx links an image to its file only when the directive is sized; without the option the
    page shows the same pixels, but the reader cannot open the image on its own. The width to
    author is the file's intrinsic width or an intentional responsive size
    (``docs/img/sensors/README.md``).
    """
    unsized = _unsized_images(rst.read_text(encoding="utf-8").splitlines())
    assert not unsized, f"{_rel(rst)}: image directive(s) without :width: at line(s) {unsized}"


@pytest.mark.parametrize("rel", sorted(NO_RELATED))
def test_allowlisted_path_exists(rel):
    """An allowlist entry for a page that is gone is noise; drop it."""
    assert (DOCS / rel).exists(), f"{rel} is allowlisted here but no longer exists; drop the entry"


@pytest.mark.parametrize("subtree", sorted(EXCLUDED_SUBTREES))
def test_excluded_subtree_is_still_excluded_from_the_build(subtree):
    """Once docs/conf.py publishes an excluded subtree, its pages are held to the skeletons too."""
    conf = (DOCS / "conf.py").read_text(encoding="utf-8")
    assert f'"{subtree}/**"' in conf, (
        f"docs/conf.py no longer excludes {subtree}; drop it from EXCLUDED_SUBTREES"
    )
